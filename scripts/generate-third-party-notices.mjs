import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  readdirSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const rootPackage = JSON.parse(
  readFileSync(path.join(projectRoot, "package.json"), "utf8"),
);
const packages = new Map();

function packageDirectory(name, nodeModulesDirectory) {
  const candidate = path.join(nodeModulesDirectory, ...name.split("/"));
  if (!existsSync(candidate)) return undefined;
  return realpathSync(candidate);
}

function dependencyDirectory(packagePath, packageName) {
  const parent = path.dirname(packagePath);
  return packageName.startsWith("@") ? path.dirname(parent) : parent;
}

function legalFiles(packagePath) {
  return readdirSync(packagePath)
    .filter((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name))
    .sort()
    .map((name) => ({
      name,
      content: readFileSync(path.join(packagePath, name), "utf8")
        .replace(/\r\n?/g, "\n")
        .split("\n")
        .map((line) => line.trimEnd())
        .join("\n")
        .trim(),
    }))
    .filter((file) => file.content);
}

function visit(name, nodeModulesDirectory) {
  const packagePath = packageDirectory(name, nodeModulesDirectory);
  if (!packagePath) return;
  const manifest = JSON.parse(
    readFileSync(path.join(packagePath, "package.json"), "utf8"),
  );
  const key = `${manifest.name}@${manifest.version}`;
  if (packages.has(key)) return;
  packages.set(key, {
    name: manifest.name,
    version: manifest.version,
    license: manifest.license ?? "See included license text",
    legalFiles: legalFiles(packagePath),
  });
  const childNodeModules = dependencyDirectory(packagePath, manifest.name);
  const dependencies = {
    ...manifest.dependencies,
    ...manifest.optionalDependencies,
  };
  for (const dependency of Object.keys(dependencies).sort())
    visit(dependency, childNodeModules);
}

for (const dependency of Object.keys(rootPackage.dependencies ?? {}).sort())
  visit(dependency, path.join(projectRoot, "node_modules"));

const licenseGroups = new Map();
const notices = [];
for (const packageInfo of packages.values()) {
  for (const file of packageInfo.legalFiles) {
    if (/^notice/i.test(file.name)) {
      notices.push({ packageInfo, file });
      continue;
    }
    const hash = createHash("sha256").update(file.content).digest("hex");
    const group = licenseGroups.get(hash) ?? {
      content: file.content,
      packages: [],
    };
    group.packages.push(`${packageInfo.name}@${packageInfo.version}`);
    licenseGroups.set(hash, group);
  }
}

const inventory = [...packages.values()]
  .sort((left, right) => left.name.localeCompare(right.name))
  .map(
    (packageInfo) =>
      `- ${packageInfo.name}@${packageInfo.version} — ${packageInfo.license}`,
  )
  .join("\n");
const licenses = [...licenseGroups.values()]
  .sort((left, right) => left.packages[0].localeCompare(right.packages[0]))
  .map(
    (group) =>
      `## ${group.packages.sort().join(", ")}\n\n${group.content}`,
  )
  .join("\n\n---\n\n");
const noticeText = notices
  .sort((left, right) =>
    left.packageInfo.name.localeCompare(right.packageInfo.name),
  )
  .map(
    ({ packageInfo, file }) =>
      `## ${packageInfo.name}@${packageInfo.version} — ${file.name}\n\n${file.content}`,
  )
  .join("\n\n---\n\n");
const output = `# Third-party notices

This file is generated by \`pnpm legal:generate\`. Inkframe is distributed
under the MIT License; see \`LICENSE\`. The packages below retain their own
copyrights and license terms.

## Electron and Chromium

Inkframe is built with Electron. Packaged applications include Electron's MIT
license as \`legal/ELECTRON_LICENSE\` and Chromium's complete notices as
\`legal/LICENSES.chromium.html\`. The upstream texts are also available from
the [Electron project](https://github.com/electron/electron).

## Production dependency inventory

${inventory}

# License texts

${licenses}

${noticeText ? `# Additional notices\n\n${noticeText}\n` : ""}`;

writeFileSync(
  path.join(projectRoot, "THIRD_PARTY_NOTICES.md"),
  output,
  "utf8",
);
console.log(`Wrote notices for ${packages.size} production packages.`);
